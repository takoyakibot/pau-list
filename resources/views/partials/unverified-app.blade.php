<h3 id="login-flow-heading" class="mt-3 font-semibold">ログインの流れ（確認されていないアプリの警告について）</h3>
<ol class="mt-2 list-decimal space-y-1 pl-6">
    <li>Google のアカウント選択画面で、再生リストを作りたいチャンネルを選びます</li>
    <li>『このアプリは Google で確認されていません』と表示されたら、『詳細』を押し、『（アプリ名またはドメイン）（安全ではないページ）に移動』のようなリンクを選びます。Google の審査が完了するまでは、この警告が表示されます</li>
    <li>YouTube の権限の確認画面で内容を確認し、『続行』を押します。権限の確認画面にチェックボックスが表示された場合は、YouTube の権限にチェックを入れてください（入れないと再生リストを作成できません）</li>
</ol>
<p class="mt-2">Google の画面には YouTube アカウントの管理という広い権限が表示されますが、使うのはチャンネルの確認・自分の限定公開動画の表示・再生リストの作成と動画の追加だけです（<a class="underline" href="{{ route('privacy') }}#data">詳しくはプライバシーポリシー</a>）</p>
