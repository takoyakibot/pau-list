                <li><strong>チャンネル主のログイン情報</strong>: Google ログインで許可いただく YouTube の権限（youtube スコープ）は、チャンネルの確認・自分の限定公開動画の表示・再生リストの作成と動画の追加にのみ使います。編集画面で動画 URL から動画を追加するときは、その動画が追加できるもの（公開の動画か、自分の限定公開の動画）かを確かめるためにも使います（確かめた結果は画面に返すだけで、保存しません）。取得するのはチャンネル ID・チャンネル名・アクセストークンだけで、メールアドレス・氏名・リフレッシュトークンは取得しません。再生リストの作成と動画の追加にあたっては、追加する動画の状態（公開設定など）を作成の直前に確認し、作成の結果を確かめるために、チャンネル主の再生リストの一覧と、作成した再生リストに入っている動画を読み取ることがあります。読み取った内容は確認にだけ使い、下の「作成の記録」に書いたもの以外は保存しません。</li>
