            <ul class="mt-3 list-disc space-y-3 pl-6">
                <li><strong>提案の内容</strong>（再生リスト名・説明・コメント・ニックネーム・選んだ動画）: 共有 URL での表示と、チャンネル主が再生リストを作成するために使います。ニックネームとコメントの入力は任意です。</li>
